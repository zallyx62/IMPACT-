import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { buildEntityDossier, getPublishedEntities } from "../app/src/data/dossier-builder.ts";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const recordsRoot = path.join(repositoryRoot, "data", "records");
const outputPath = path.join(repositoryRoot, "app", "src", "data", "public-records.generated.ts");
const collections = [
  "entities",
  "sources",
  "claims",
  "evidence",
  "relationships",
  "campaigns",
  "responses",
  "commitments",
];

async function loadCollection(name) {
  const directory = path.join(recordsRoot, name);
  const entries = await readdir(directory, { withFileTypes: true });
  const records = [];
  for (const entry of entries.filter((item) => item.isFile() && item.name.endsWith(".json")).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const record = JSON.parse(await readFile(path.join(directory, entry.name), "utf8"));
    records.push(record);
  }
  return records;
}

const data = Object.fromEntries(
  await Promise.all(collections.map(async (name) => [name, await loadCollection(name)])),
);

const entities = getPublishedEntities(data);
const dossiers = entities
  .map((entity) => buildEntityDossier(entity.id, data))
  .filter(Boolean);

function uniqueRecords(records) {
  return [...new Map(records.map((record) => [record.id, record])).values()];
}

const publicRecords = {
  entities,
  sources: uniqueRecords(dossiers.flatMap((dossier) => dossier.sources)),
  claims: uniqueRecords(dossiers.flatMap((dossier) => dossier.claims)),
  evidence: uniqueRecords(dossiers.flatMap((dossier) => dossier.evidence)),
  relationships: uniqueRecords(dossiers.flatMap((dossier) => dossier.relationships)),
  campaigns: uniqueRecords(dossiers.flatMap((dossier) => dossier.campaigns)),
  responses: uniqueRecords(dossiers.flatMap((dossier) => dossier.responses)),
  commitments: uniqueRecords(dossiers.flatMap((dossier) => dossier.commitments)),
};

const output = [
  "// Generated by scripts/generate-public-records.mjs. Do not edit manually.",
  "// Only records that pass the editorial publication gate are included in the public Web bundle.",
  `export const publicRecords = ${JSON.stringify(publicRecords, null, 2)};`,
  "",
].join("\n");

await writeFile(outputPath, output, "utf8");
const counts = collections.map((name) => `${name}: ${publicRecords[name].length}`).join(", ");
console.log(`Generated filtered public editorial data (${counts}).`);
